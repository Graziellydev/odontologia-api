package br.com.unicatolica.odontologia_api;

import br.com.unicatolica.odontologia_api.model.Perfil;
import br.com.unicatolica.odontologia_api.security.PasswordResetCodeSender;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.test.web.servlet.MockMvc;

import static br.com.unicatolica.odontologia_api.CsrfTestSupport.csrf;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotEquals;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyLong;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.reset;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.content;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

@SpringBootTest(properties = {
        "app.auth.recovery.rate-limit.max-requests=1000",
        "spring.jpa.database-platform=org.hibernate.dialect.H2Dialect"
})
@AutoConfigureMockMvc
@ActiveProfiles("test")
class PasswordRecoveryIntegrationTest {

    private static final String EMAIL = "aluno.recovery@teste.invalid";
    private static final String MATRICULA = "202600987";
    private static final String SENHA_ANTIGA = "SenhaAntigaSegura123";

    @Autowired private MockMvc mvc;
    @Autowired private JdbcTemplate jdbc;
    @Autowired private PasswordEncoder encoder;
    @MockitoBean private PasswordResetCodeSender sender;

    @BeforeEach
    void prepararSchemaEConta() {
        reset(sender);
        jdbc.execute("DROP TABLE IF EXISTS password_reset_tokens");
        jdbc.execute("DROP TABLE IF EXISTS usuarios");
        jdbc.execute("""
                CREATE TABLE usuarios (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    nome VARCHAR(150) NOT NULL,
                    email VARCHAR(150) NOT NULL UNIQUE,
                    senha_hash VARCHAR(255) NOT NULL,
                    perfil VARCHAR(30) NOT NULL,
                    matricula_ou_registro VARCHAR(50) UNIQUE,
                    semestre_atual INTEGER,
                    ativo BOOLEAN NOT NULL DEFAULT TRUE,
                    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("""
                CREATE TABLE password_reset_tokens (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
                    codigo_hash VARCHAR(255) NOT NULL,
                    expira_em TIMESTAMP WITH TIME ZONE NOT NULL,
                    usado BOOLEAN NOT NULL DEFAULT FALSE,
                    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    tentativas_falhas INTEGER NOT NULL DEFAULT 0
                )
                """);
        jdbc.update("INSERT INTO usuarios (nome,email,senha_hash,perfil,matricula_ou_registro,ativo) VALUES (?,?,?,?,?,TRUE)",
                "Aluno Recuperação", EMAIL, encoder.encode(SENHA_ANTIGA), Perfil.ALUNO.name(), MATRICULA);
    }

    @Test
    void loginValidoPorMatriculaEInvalidoUsamRespostaGenerica() throws Exception {
        mvc.perform(post("/api/auth/login").with(csrf()).contentType("application/json")
                        .content("{\"identificador\":\"" + MATRICULA + "\",\"senha\":\"" + SENHA_ANTIGA + "\"}"))
                .andExpect(status().isOk())
                .andExpect(content().string(org.hamcrest.Matchers.containsString("ALUNO")));

        String erroEmail = mvc.perform(post("/api/auth/login").with(csrf()).contentType("application/json")
                        .content("{\"identificador\":\"nao-existe@teste.invalid\",\"senha\":\"incorreta\"}"))
                .andExpect(status().isUnauthorized()).andReturn().getResponse().getContentAsString();
        String erroSenha = mvc.perform(post("/api/auth/login").with(csrf()).contentType("application/json")
                        .content("{\"identificador\":\"" + EMAIL + "\",\"senha\":\"incorreta\"}"))
                .andExpect(status().isUnauthorized()).andReturn().getResponse().getContentAsString();

        assertEquals("Login ou senha inválidos", erroEmail);
        assertEquals(erroEmail, erroSenha);
    }

    @Test
    void solicitacaoParaContaExistenteOuInexistenteRetornaMesmoHttp200Neutro() throws Exception {
        String existente = mvc.perform(post("/api/auth/esqueci-senha").with(csrf()).contentType("application/json")
                        .content("{\"identificador\":\"" + EMAIL + "\"}"))
                .andExpect(status().isOk()).andReturn().getResponse().getContentAsString();
        String inexistente = mvc.perform(post("/api/auth/esqueci-senha").with(csrf()).contentType("application/json")
                        .content("{\"identificador\":\"ausente@teste.invalid\"}"))
                .andExpect(status().isOk()).andReturn().getResponse().getContentAsString();
        assertEquals(existente, inexistente);
        verify(sender).enviar(anyLong(), eq(EMAIL), eq("Aluno Recuperação"), any());
        assertNotEquals("", existente);
    }

    @Test
    void codigoValidoRedefineSenhaPermiteLoginEConsumidoNaoPodeSerReusado() throws Exception {
        solicitarCodigo();
        org.mockito.ArgumentCaptor<String> codigoCapturado = org.mockito.ArgumentCaptor.forClass(String.class);
        verify(sender).enviar(anyLong(), eq(EMAIL), eq("Aluno Recuperação"), codigoCapturado.capture());
        String codigo = codigoCapturado.getValue();
        org.junit.jupiter.api.Assertions.assertEquals(6, codigo.length());

        redefinir(codigo, "NovaSenhaSegura123").andExpect(status().isOk());
        assertEquals(true, jdbc.queryForObject("SELECT usado FROM password_reset_tokens", Boolean.class));
        org.junit.jupiter.api.Assertions.assertTrue(encoder.matches("NovaSenhaSegura123", jdbc.queryForObject(
                "SELECT senha_hash FROM usuarios WHERE email=?", String.class, EMAIL)));

        mvc.perform(post("/api/auth/login").with(csrf()).contentType("application/json")
                        .content("{\"identificador\":\"" + EMAIL + "\",\"senha\":\"NovaSenhaSegura123\"}"))
                .andExpect(status().isOk());
        mvc.perform(post("/api/auth/login").with(csrf()).contentType("application/json")
                        .content("{\"identificador\":\"" + EMAIL + "\",\"senha\":\"" + SENHA_ANTIGA + "\"}"))
                .andExpect(status().isUnauthorized());
        redefinir(codigo, "OutraSenhaSegura123").andExpect(status().isBadRequest());
    }

    @Test
    void codigoInvalidoOuExpiradoRetorna400() throws Exception {
        solicitarCodigo();
        org.mockito.ArgumentCaptor<String> codigoCapturado = org.mockito.ArgumentCaptor.forClass(String.class);
        verify(sender).enviar(anyLong(), eq(EMAIL), eq("Aluno Recuperação"), codigoCapturado.capture());
        String codigo = codigoCapturado.getValue();
        String incorreto = (codigo.charAt(0) == '0' ? "1" : "0") + codigo.substring(1);
        redefinir(incorreto, "NovaSenhaSegura123").andExpect(status().isBadRequest());

        jdbc.update("UPDATE password_reset_tokens SET expira_em=CURRENT_TIMESTAMP - INTERVAL '1' HOUR");
        redefinir(codigo, "NovaSenhaSegura123").andExpect(status().isBadRequest());
    }

    private void solicitarCodigo() throws Exception {
        mvc.perform(post("/api/auth/esqueci-senha").with(csrf()).contentType("application/json")
                .content("{\"identificador\":\"" + EMAIL + "\"}")).andExpect(status().isOk());
    }

    private org.springframework.test.web.servlet.ResultActions redefinir(String codigo, String senha) throws Exception {
        return mvc.perform(post("/api/auth/redefinir-senha").with(csrf()).contentType("application/json")
                .content("{\"identificador\":\"" + EMAIL + "\",\"codigo\":\"" + codigo
                        + "\",\"novaSenha\":\"" + senha + "\"}"));
    }
}
