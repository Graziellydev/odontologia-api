package br.com.unicatolica.odontologia_api.satisfacao.repository;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Map;
import java.util.UUID;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import br.com.unicatolica.odontologia_api.satisfacao.repository.RelatorioSatisfacaoRepository.LinhaAvaliacao;
import br.com.unicatolica.odontologia_api.satisfacao.repository.RelatorioSatisfacaoRepository.Resumo;

class RelatorioSatisfacaoRepositoryH2Test {

    private JdbcTemplate jdbc;
    private RelatorioSatisfacaoRepository repository;

    @BeforeEach
    void prepararBanco() {
        String nome = "satisfacao" + UUID.randomUUID().toString().replace("-", "");
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:" + nome + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(dataSource);

        jdbc.execute("CREATE TABLE turmas (id BIGINT PRIMARY KEY, semestre_letivo VARCHAR(6) NOT NULL)");
        jdbc.execute("CREATE TABLE usuarios (id BIGINT PRIMARY KEY, nome VARCHAR(150) NOT NULL)");
        jdbc.execute("CREATE TABLE consultas (id BIGINT PRIMARY KEY, paciente_id BIGINT NOT NULL, "
                + "aluno_id BIGINT NOT NULL, turma_id BIGINT NOT NULL)");
        jdbc.execute("CREATE TABLE avaliacoes_satisfacao (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "consulta_id BIGINT NOT NULL UNIQUE, nota INT, comentario VARCHAR(1000), "
                + "data_resposta TIMESTAMP WITH TIME ZONE)");

        jdbc.update("INSERT INTO turmas (id, semestre_letivo) VALUES (1, '2026.1')");
        jdbc.update("INSERT INTO turmas (id, semestre_letivo) VALUES (2, '2026.2')");
        jdbc.update("INSERT INTO usuarios (id, nome) VALUES (10, 'Aluno Um')");
        jdbc.update("INSERT INTO usuarios (id, nome) VALUES (11, 'Aluno Dois')");

        // paciente_id 20 existe só na consulta: o relatório não pode devolvê-lo
        jdbc.update("INSERT INTO consultas VALUES (100, 20, 10, 2)");
        jdbc.update("INSERT INTO consultas VALUES (101, 20, 11, 2)");
        jdbc.update("INSERT INTO consultas VALUES (102, 20, 10, 2)");
        jdbc.update("INSERT INTO consultas VALUES (103, 20, 10, 1)");

        avaliacao(100, 5, "Ótimo", "2026-11-20T10:00:00-03:00");
        avaliacao(101, 4, null, "2026-11-21T10:00:00-03:00");
        avaliacao(102, null, null, null); // pesquisa enviada, paciente não respondeu
        avaliacao(103, 3, "Demorou", "2026-05-10T10:00:00-03:00");

        repository = new RelatorioSatisfacaoRepository(jdbc);
    }

    private void avaliacao(long consultaId, Integer nota, String comentario, String dataResposta) {
        jdbc.update("INSERT INTO avaliacoes_satisfacao (consulta_id, nota, comentario, data_resposta) "
                        + "VALUES (?, ?, ?, ?)",
                consultaId, nota, comentario, dataResposta == null ? null : OffsetDateTime.parse(dataResposta));
    }

    @Test
    void mediaGeralIgnoraPesquisaSemResposta() {
        Resumo resumo = repository.resumo(null);

        assertEquals(3, resumo.total());
        assertEquals(4.0, resumo.media(), 0.001);
    }

    @Test
    void mediaPorSemestre() {
        Resumo resumo = repository.resumo("2026.2");

        assertEquals(2, resumo.total());
        assertEquals(4.5, resumo.media(), 0.001);
    }

    @Test
    void semRespostasNoPeriodoNaoHaMedia() {
        Resumo resumo = repository.resumo("2027.1");

        assertEquals(0, resumo.total());
        assertNull(resumo.media());
    }

    @Test
    void contaRespostasPorNota() {
        Map<Integer, Long> contagem = repository.contagemPorNota("2026.2");

        assertEquals(Map.of(5, 1L, 4, 1L), contagem);
    }

    @Test
    void listaDaMaisRecenteParaAMaisAntigaEPagina() {
        List<LinhaAvaliacao> todas = repository.listar(null, 10, 0L);

        assertEquals(3, todas.size());
        assertEquals(List.of(4, 5, 3), todas.stream().map(LinhaAvaliacao::nota).toList());

        List<LinhaAvaliacao> segundaPagina = repository.listar(null, 1, 1L);
        assertEquals(1, segundaPagina.size());
        assertEquals(5, segundaPagina.get(0).nota());
    }

    @Test
    void listaTrazAlunoDataEComentario() {
        List<LinhaAvaliacao> linhas = repository.listar("2026.2", 10, 0L);

        assertEquals(2, linhas.size());
        assertEquals("Aluno Dois", linhas.get(0).aluno());
        assertNull(linhas.get(0).comentario());
        assertEquals("Aluno Um", linhas.get(1).aluno());
        assertEquals("Ótimo", linhas.get(1).comentario());
        assertNotNull(linhas.get(1).dataResposta());
    }

    @Test
    void listaOsSemestresCadastrados() {
        assertEquals(List.of("2026.2", "2026.1"), repository.listarSemestres());
    }
}